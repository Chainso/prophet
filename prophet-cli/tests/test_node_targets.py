EXAMPLE_ROOT = PROJECT_ROOT / "examples" / "java" / "prophet_example_spring"


class NodeTargetTests(unittest.TestCase):
    def _base_cfg(self) -> dict:
        cfg = load_config(EXAMPLE_ROOT / "prophet.yaml")
        cfg = copy.deepcopy(cfg)
        cfg["generation"]["targets"] = ["sql", "openapi", "node_express", "manifest"]
        return cfg

    def _ontology(self):
        return parse_ontology((EXAMPLE_ROOT / "ontology" / "local" / "main.prophet").read_text(encoding="utf-8"))

    def _enum_ontology(self):
        return parse_ontology(
            """
ontology CommerceLocal {
  version "0.1.0"

  enum OrderStatus {
    value Pending {
      name "Pending"
    }

    value Approved {
      name "Approved"
    }
  }

  object Order {
    field orderId {
      type string
      key primary
    }

    field status {
      type OrderStatus
    }
  }

  action createOrder {
    input {
      field status {
        type OrderStatus
      }
    }

    output {
      field orderId {
        type string
      }
    }
  }
}
"""
        )

    def _state_field_event_ontology(self):
        return parse_ontology(
            """
ontology CommerceLocal {
  version "0.1.0"

  enum OrderStatus {
    value Created
    value Approved
  }

  object Order {
    field orderId {
      type string
      key primary
    }

    field status {
      type OrderStatus
      state
      initial Created
    }
  }

  event OrderApproved {
    field order {
      type ref(Order)
    }
  }

  action approveOrder {
    input {
      field order {
        type ref(Order)
      }
    }

    output event OrderApproved
  }
}
"""
        )

    def test_node_prisma_stack_generates_expected_artifacts(self) -> None:
        cfg = self._base_cfg()
        cfg["generation"]["stack"] = {"id": "node_express_prisma"}
        cfg["generation"]["targets"] = ["sql", "openapi", "node_express", "prisma", "manifest"]

        ir = build_ir(self._ontology(), cfg)
        with tempfile.TemporaryDirectory(prefix="prophet-node-prisma-") as tmp:
            outputs = build_generated_outputs(ir, cfg, root=Path(tmp))

        self.assertIn("gen/node-express/src/generated/index.ts", outputs)
        self.assertIn("gen/node-express/src/generated/action-routes.ts", outputs)
        self.assertIn("gen/node-express/src/generated/prisma-adapters.ts", outputs)
        self.assertIn("gen/node-express/prisma/schema.prisma", outputs)
        self.assertIn("gen/manifest/generated-files.json", outputs)
        self.assertIn("constructor(private readonly client: PrismaClient)", outputs["gen/node-express/src/generated/prisma-adapters.ts"])
        self.assertIn("this.delegate.findMany", outputs["gen/node-express/src/generated/prisma-adapters.ts"])
        self.assertIn("this.delegate.upsert", outputs["gen/node-express/src/generated/prisma-adapters.ts"])
        self.assertNotIn("implement repository binding logic", outputs["gen/node-express/src/generated/prisma-adapters.ts"])
        self.assertIn('status String @default("Created")', outputs["gen/node-express/prisma/schema.prisma"])
        self.assertNotIn("enum OrderStatus {", outputs["gen/node-express/prisma/schema.prisma"])
        self.assertNotIn("__prophet_state", outputs["gen/node-express/prisma/schema.prisma"])
        self.assertNotIn("model OrderStateHistory", outputs["gen/node-express/prisma/schema.prisma"])
        self.assertTrue(
            outputs["gen/node-express/src/generated/index.ts"].startswith("// Code generated by prophet-cli. DO NOT EDIT.")
        )
        self.assertNotIn("Generated", outputs["gen/node-express/src/generated/index.ts"])
        self.assertNotIn("TransitionServices", outputs["gen/node-express/src/generated/index.ts"])

        manifest = json.loads(outputs["gen/manifest/generated-files.json"])
        self.assertEqual(manifest["stack"]["id"], "node_express_prisma")

