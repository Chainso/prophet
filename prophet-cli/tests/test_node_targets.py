        self.assertIn("name: 'status'", typeorm_outputs["gen/node-express/src/generated/typeorm-entities.ts"])
        self.assertIn("status!: Domain.OrderStatus;", typeorm_outputs["gen/node-express/src/generated/typeorm-entities.ts"])

        mongoose_cfg = self._base_cfg()
        mongoose_cfg["generation"]["stack"] = {"id": "node_express_mongoose"}
        mongoose_cfg["generation"]["targets"] = ["openapi", "node_express", "mongoose", "manifest"]
